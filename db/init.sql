CREATE EXTENSION IF NOT EXISTS postgis;

CREATE TABLE IF NOT EXISTS transactions (
    id              SERIAL PRIMARY KEY,
    card_token      TEXT           NOT NULL,
    location        geography(Point, 4326) NOT NULL,
    transacted_at   TIMESTAMPTZ    NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_transactions_card_token ON transactions (card_token);
CREATE INDEX idx_transactions_transacted_at ON transactions (transacted_at);
CREATE INDEX idx_transactions_location   ON transactions USING GIST (location);

